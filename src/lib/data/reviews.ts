/**
 * Calculate rating summary metrics for a product
 */
export interface ProductRatingSummary {
  averageRating: number;
  totalCount: number;
  distribution: {
    star: number;
    count: number;
    percentage: number;
  }[];
  recommendationRate: number;
}

export function getProductRatingSummary(
  productSlug: string,
  fallbackAverage: number = 4.9,
  fallbackCount: number = 24
): ProductRatingSummary {
  const reviews = getReviewsForProduct(productSlug);

  if (reviews.length === 0) {
    // Generate realistic distribution based on fallback
    const fiveStarCount = Math.round(fallbackCount * 0.92);
    const fourStarCount = fallbackCount - fiveStarCount;

    return {
      averageRating: fallbackAverage,
      totalCount: fallbackCount,
      distribution: [
        {
          star: 5,
          count: fiveStarCount,
          percentage: Math.round((fiveStarCount / fallbackCount) * 100),
        },
        {
          star: 4,
          count: fourStarCount,
          percentage: Math.round((fourStarCount / fallbackCount) * 100),
        },
        { star: 3, count: 0, percentage: 0 },
        { star: 2, count: 0, percentage: 0 },
        { star: 1, count: 0, percentage: 0 },
      ],
      recommendationRate: 99,
    };
  }

  const totalCount = reviews.length;
  const ratingSum = reviews.reduce((acc, r) => acc + r.rating, 0);
  const averageRating = Number((ratingSum / totalCount).toFixed(1));

  const distribution = [5, 4, 3, 2, 1].map((star) => {
    const count = reviews.filter((r) => r.rating === star).length;
    const percentage = totalCount > 0 ? Math.round((count / totalCount) * 100) : 0;
    return { star, count, percentage };
  });

  const positiveReviews = reviews.filter((r) => r.rating >= 4).length;
  const recommendationRate =
    totalCount > 0 ? Math.round((positiveReviews / totalCount) * 100) : 99;

  return {
    averageRating,
    totalCount,
    distribution,
    recommendationRate,
  };
}

