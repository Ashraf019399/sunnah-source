export async function POST(req: NextRequest) {
  try {
    const body = await req.json();
    const messages: ChatMessage[] = body.messages || [];

    if (!Array.isArray(messages) || messages.length === 0) {
      return NextResponse.json(
        { error: "No messages provided." },
        { status: 400 }
      );
    }

    const apiKey = process.env.GEMINI_API_KEY;

    if (!apiKey) {
      console.warn("GEMINI_API_KEY is not defined. Falling back to local concierge.");
      return NextResponse.json({
        reply: generateLocalFallbackResponse(messages[messages.length - 1]?.content || ""),
      });
    }

    // Format conversation history for Gemini API
    // Ensure alternating user/model roles and non-empty content
    const contents = messages
      .filter((m) => m && typeof m.content === "string" && m.content.trim().length > 0)
      .map((m) => ({
        role: m.role === "assistant" ? "model" : "user",
        parts: [{ text: m.content.trim() }],
      }));

    if (contents.length === 0) {
      return NextResponse.json(
        { error: "Empty message payload." },
        { status: 400 }
      );
    }

    // Candidate Gemini models with automatic fallback
    const CANDIDATE_MODELS = [
      "gemini-1.5-flash",
      "gemini-3.5-flash-lite",
      "gemini-3.8-flash",
      "gemini-flash-latest",
    ];

    let generatedText: string | null = null;

    for (const model of CANDIDATE_MODELS) {
      try {
        const response = await fetch(
          `https://generativelanguage.googleapis.com/v1beta/models/${model}:generateContent?key=${apiKey}`,
          {
            method: "POST",
            headers: {
              "Content-Type": "application/json",
              "x-goog-api-key": apiKey,
            },
            body: JSON.stringify({
              systemInstruction: {
                parts: [{ text: SYSTEM_INSTRUCTION }],
              },
              contents,
              generationConfig: {
                temperature: 0.7,
                topK: 40,
                topP: 0.95,
                maxOutputTokens: 1024,
              },
            }),
          }
        );

        if (response.ok) {
          const data = await response.json();
          const text = data?.candidates?.[0]?.content?.parts?.[0]?.text;
          if (text) {
            generatedText = text;
            break;
          }
        } else {
          console.warn(`Model ${model} returned HTTP ${response.status}. Trying next candidate...`);
        }
      } catch (callErr) {
        console.warn(`Failed to call ${model}:`, callErr);
      }
    }

    if (!generatedText) {
      const lastUserQuery = messages[messages.length - 1]?.content || "";
      return NextResponse.json({
        reply: generateLocalFallbackResponse(lastUserQuery),
      });
    }

    return NextResponse.json({ reply: generatedText });
  } catch (error) {
    console.error("Chat API error:", error);
    return NextResponse.json({
      reply:
        "আসসালামু আলাইকুম ওয়া রাহমাতুল্লাহ। সাময়িক প্রযুক্তিগত সমস্যার কারণে উত্তর দিতে সামান্য বিলম্ব হচ্ছে। আমাদের খাঁটি পণ্য, অর্ডার বা পরামর্শের জন্য সরাসরি আমাদের হটলাইন অথবা হোয়াটসঅ্যাপে যোগাযোগ করুন: **01914-612007**। আমরা সার্বক্ষণিক আপনার সেবায় নিয়োজিত।",
    });
  }
}

